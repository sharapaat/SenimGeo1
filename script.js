// ӘР АДАМДЫ КӨРСЕТУ
// ==========================================

function loadProgressPeople() {

    const container =
        document.getElementById(
            "progressResultsList"
        );


    if (!container) return;


    container.innerHTML = "";


    progressData.forEach((person, index) => {

        const first =
            person.tests[0];

        const second =
            person.tests[1];

        const third =
            person.tests[2];


        const growth =
            third - first;


        const chartId =
            "progressChart" + index;


        container.innerHTML += `

            <div class="individual-progress">

                <div class="individual-progress-header">

                    <div>

                        <h3>
                            ${person.name}
                        </h3>

                        <p>
                            ${person.group}
                            •
                            ${person.topic}
                        </p>

                    </div>

                    <div class="final-result">

                        ${third}%

                    </div>

                </div>


                <div class="individual-chart">

                    <canvas
                        id="${chartId}">
                    </canvas>

                </div>


                <div class="individual-results">

                    <div>

                        <span>
                            1-тест
                        </span>

                        <strong>
                            ${first}%
                        </strong>

                    </div>


                    <span class="result-arrow">
                        →
                    </span>


                    <div>

                        <span>
                            2-тест
                        </span>

                        <strong>
                            ${second}%
                        </strong>

                    </div>


                    <span class="result-arrow">
                        →
                    </span>


                    <div>

                        <span>
                            3-тест
                        </span>

                        <strong>
                            ${third}%
                        </strong>

                    </div>


                    <div class="growth-result">

                        ${
                            growth > 0
                                ? "↑ +" + growth + "%"
                                : growth === 0
                                    ? "0%"
                                    : "↓ " + Math.abs(growth) + "%"
                        }

                    </div>

                </div>

            </div>

        `;

    });


    // Диаграммаларды салу

    progressData.forEach((person, index) => {

        drawProgressChart(
            "progressChart" + index,
            person.tests
        );

    });

}


