/* ==========================================
   ЖАУАПТЫ ТЕКСЕРУ
========================================== */

function checkRegionAnswer(
    selectedRegion,
    selectedPath
) {

    /*
       Бір сұраққа бір ғана жауап
    */

    if (mapQuestionAnswered) {
        return;
    }


    const correctRegion =
        regionNameMap[selectedRegion]
        || selectedRegion;


    const neededRegion =
        regionQuestions[mapQuestionIndex];


    mapQuestionAnswered = true;


    /*
       ======================================
       ДҰРЫС ЖАУАП
       ======================================
    */

    if (
        normalizeRegion(correctRegion) ===
        normalizeRegion(neededRegion)
    ) {

        /*
           Басқан облыс ЖАСЫЛ
        */

        selectedPath.classList.add(
            "region-correct"
        );


        document.getElementById(
            "mapAnswerMessage"
        ).innerHTML = `
            <span class="map-correct">
                ✅ Дұрыс! ${neededRegion}
            </span>
        `;

    }


    /*
       ======================================
       ҚАТЕ ЖАУАП
       ======================================
    */

    else {

        /*
           Сен басқан облыс ҚЫЗЫЛ
        */

        selectedPath.classList.add(
            "region-wrong"
        );


        /*
           Дұрыс облысты іздейміз
        */

        document
            .querySelectorAll(".region-svg")
            .forEach(path => {

                const mapName =
                    path.dataset.region;


                const fullName =
                    regionNameMap[mapName]
                    || mapName;


                /*
                   Дұрыс облыс болса
                   ЖАСЫЛ қыламыз
                */

                if (
                    normalizeRegion(fullName) ===
                    normalizeRegion(neededRegion)
                ) {

                    path.classList.add(
                        "region-correct"
                    );

                }

            });


        document.getElementById(
            "mapAnswerMessage"
        ).innerHTML = `
            <span class="map-wrong">
                ❌ Қате! Дұрыс облыс:
                <strong>${neededRegion}</strong>
            </span>
        `;

    }


    /*
       Келесі облыс
    */

    document.getElementById(
        "mapNextButton"
    ).style.display = "block";

}


