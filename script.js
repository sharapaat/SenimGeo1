function loadProgressPage() {

    const total =
        progressData.length;


    // Барлық нәтижелер

    let allResults = [];

    progressData.forEach(person => {

        person.tests.forEach(result => {

            allResults.push(result);

        });

    });


    // Орташа нәтиже

    const average =
        Math.round(
            allResults.reduce(
                (sum, value) => sum + value,
                0
            ) / allResults.length
        );


    // 100% алғандар

    const perfect =
        progressData.filter(person => {

            return person.tests[2] === 100;

        }).length;


    // Прогресс жасағандар

    const improved =
        progressData.filter(person => {

            return person.tests[2] > person.tests[0];

        }).length;


    document.getElementById("progressTotal").textContent =
        total;

    document.getElementById("progressAverage").textContent =
        average + "%";

    document.getElementById("progressPerfect").textContent =
        perfect;

    document.getElementById("progressImproved").textContent =
        improved;


    // Адамдардың диаграммалары

    loadProgressPeople();

}


