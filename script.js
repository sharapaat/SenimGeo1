// ЖЕКЕ ДИАГРАММА
// ==========================================

function drawProgressChart(canvasId, values) {

    const canvas =
        document.getElementById(canvasId);


    if (!canvas) return;


    const ctx =
        canvas.getContext("2d");


    const width =
        canvas.clientWidth || 700;


    const height =
        260;


    const dpr =
        window.devicePixelRatio || 1;


    canvas.width =
        width * dpr;

    canvas.height =
        height * dpr;


    ctx.setTransform(
        dpr,
        0,
        0,
        dpr,
        0,
        0
    );


    const left =
        45;

    const right =
        25;

    const top =
        25;

    const bottom =
        45;


    const chartWidth =
        width - left - right;


    const chartHeight =
        height - top - bottom;


    ctx.clearRect(
        0,
        0,
        width,
        height
    );


    // ------------------------------------------
    // 0 - 100% тор
    // ------------------------------------------

    for (
        let value = 0;
        value <= 100;
        value += 20
    ) {

        const y =
            height -
            bottom -
            (value / 100) *
            chartHeight;


        ctx.beginPath();

        ctx.moveTo(
            left,
            y
        );

        ctx.lineTo(
            width - right,
            y
        );


        ctx.strokeStyle =
            "#e2e8f0";

        ctx.lineWidth =
            1;

        ctx.stroke();


        ctx.fillStyle =
            "#64748b";

        ctx.font =
            "12px Arial";

        ctx.textAlign =
            "right";


        ctx.fillText(
            value + "%",
            left - 8,
            y + 4
        );

    }


    // ------------------------------------------
    // 3 НҮКТЕ
    // ------------------------------------------

    const x = [

        left,

        left + chartWidth / 2,

        width - right

    ];


    const points =
        values.map((value, index) => {

            return {

                x: x[index],

                y:
                    height -
                    bottom -
                    (value / 100) *
                    chartHeight

            };

        });


    // ------------------------------------------
    // СЫЗЫҚ
    // ------------------------------------------

    ctx.beginPath();


    points.forEach((point, index) => {

        if (index === 0) {

            ctx.moveTo(
                point.x,
                point.y
            );

        } else {

            ctx.lineTo(
                point.x,
                point.y
            );

        }

    });


    ctx.strokeStyle =
        "#2563eb";

    ctx.lineWidth =
        4;

    ctx.lineJoin =
        "round";

    ctx.lineCap =
        "round";

    ctx.stroke();


    // ------------------------------------------
    // НҮКТЕЛЕР ЖӘНЕ %
    // ------------------------------------------

    points.forEach((point, index) => {

        ctx.beginPath();

        ctx.arc(
            point.x,
            point.y,
            7,
            0,
            Math.PI * 2
        );


        ctx.fillStyle =
            "#ffffff";

        ctx.fill();


        ctx.beginPath();

        ctx.arc(
            point.x,
            point.y,
            5,
            0,
            Math.PI * 2
        );


        ctx.fillStyle =
            "#2563eb";

        ctx.fill();


        ctx.fillStyle =
            "#1e293b";

        ctx.font =
            "bold 13px Arial";

        ctx.textAlign =
            "center";


        ctx.fillText(
            values[index] + "%",
            point.x,
            point.y - 14
        );

    });


    // ------------------------------------------
    // ТЕСТ АТАУЛАРЫ
    // ------------------------------------------

    ctx.fillStyle =
        "#64748b";

    ctx.font =
        "12px Arial";

    ctx.textAlign =
        "center";


    ctx.fillText(
        "1-тест",
        x[0],
        height - 15
    );


    ctx.fillText(
        "2-тест",
        x[1],
        height - 15
    );


    ctx.fillText(
        "3-тест",
        x[2],
        height - 15
    );

}


