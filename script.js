let searchMarker = null;

async function searchLocation() {

    const input = document.getElementById("mapSearchInput");
    const result = document.getElementById("searchResult");

    const query = input.value.trim();

    if (!query) {
        result.textContent = "Іздеу үшін орынның атауын жазыңыз.";
        return;
    }

    result.textContent = "Ізделуде...";

    try {

        const url =
            "https://nominatim.openstreetmap.org/search?format=json&limit=1&q=" +
            encodeURIComponent(query);

        const response = await fetch(url);

        const data = await response.json();

        if (data.length === 0) {
            result.textContent = "Бұл орын табылмады.";
            return;
        }

        const place = data[0];

        const lat = parseFloat(place.lat);
        const lon = parseFloat(place.lon);

        mainMap.setView([lat, lon], 10);

        // Бұрынғы іздеу маркерін өшіру
        if (searchMarker) {
            mainMap.removeLayer(searchMarker);
        }

        // Жаңа маркер
        searchMarker = L.marker([lat, lon])
            .addTo(mainMap)
            .bindPopup(`
                <strong>${place.display_name}</strong>
            `)
            .openPopup();

        result.textContent =
            "Табылды: " + place.display_name;

    } catch (error) {

        console.error(error);

        result.textContent =
            "Іздеу кезінде қате пайда болды.";
    }
}


